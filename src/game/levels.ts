/**
 * Automatically tests and verifies all handcrafted levels using the BFS solver.
 * Returns detailed diagnostic reports for each level.
 */
export function verifyAllLevels(): { levelId: string; name: string; result: SolverResult }[] {
  return HANDCRAFTED_LEVELS.map((level) => {
    const result = solveLevel(level);
    return {
      levelId: level.id,
      name: level.name,
      result,
    };
  });
}
